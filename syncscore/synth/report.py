"""Turn benchmark rows into a markdown report and two figures."""
from __future__ import annotations

from collections import defaultdict
from pathlib import Path

import numpy as np

from ..viz.style import INK, MUTED, SERIES, apply_style


def _mean(values):
    values = [v for v in values if v is not None]
    return float(np.mean(values)) if values else None


def _fmt(value, digits=1, pct=False):
    if value is None:
        return "-"
    return f"{value * 100:.0f}%" if pct else f"{value:.{digits}f}"


def _group(rows, sweep):
    by_label = defaultdict(list)
    for row in rows:
        if row["sweep"] == sweep:
            by_label[(row["value"], row["label"])].append(row)
    return [(label, items) for (_, label), items in sorted(by_label.items(), key=lambda kv: kv[0][0])]


def _metric(items, scope, key):
    return _mean([row[scope][key] for row in items if scope in row])


def write_report(rows: list[dict], out: Path) -> dict:
    lines = ["# SyncScore validation (synthetic)", "",
             "Generated by `syncscore validate`. Truth is relative to the median member. "
             "*Reliable* windows are the ones the method did not flag as unmeasurable. "
             f"*Confidently wrong* = reliable windows off by more than 30 ms.", ""]
    summary = {}

    # Headline: per member offsets.
    lines += ["## Headline: known shifts and a known limb error", "",
              "7 members, 40 s at 30 fps, offsets 0/0/0/-33/+33/+67/+133 ms, member 2's left elbow +20° "
              "(10-20 s), member 6's right knee +15° (24-34 s). *Realistic* adds keypoint noise "
              "(1% of height), 3% dropped keypoints and 3° of personal style per joint.", ""]
    head = {label: items for label, items in _group(rows, "headline")}
    lines += ["| member | true (ms) | clean: estimated | realistic: estimated |", "|---|---|---|---|"]
    members = len(next(iter(head.values()))[0]["members"])
    per_condition = {}
    for label, items in head.items():
        est = np.array([[m["estimated_ms"] if m["estimated_ms"] is not None else np.nan for m in row["members"]] for row in items])
        per_condition[label] = (np.nanmean(est, axis=0), np.nanstd(est, axis=0), items[0]["members"])
    for i in range(members):
        true = per_condition["clean"][2][i]["true_ms"]
        cells = [f"{per_condition[c][0][i]:+.1f} ± {per_condition[c][1][i]:.1f}" for c in ("clean", "realistic")]
        lines.append(f"| M{i + 1} | {true:+.0f} | {cells[0]} | {cells[1]} |")
    lines += ["", "| condition | window MAE (ms) | 95th pct (ms) | coverage | confidently wrong |", "|---|---|---|---|---|"]
    for label, items in head.items():
        lines.append(f"| {label} | {_fmt(_metric(items, 'all', 'mae_ms'))} | {_fmt(_metric(items, 'all', 'p95_ms'))} | "
                     f"{_fmt(_metric(items, 'all', 'coverage'), pct=True)} | {_fmt(_metric(items, 'all', 'confidently_wrong'), pct=True)} |")
        summary[f"headline_{label}_mae_ms"] = _metric(items, "all", "mae_ms")
    lines += ["", "| condition | limb | true | measured | others on that bone | right bone named | right part named |", "|---|---|---|---|---|---|---|"]
    for label, items in head.items():
        for k, limb in enumerate(items[0]["limbs"]):
            got = [row["limbs"][k] for row in items]
            lines.append(f"| {label} | M{limb['member'] + 1} {limb['true_bone']} | {limb['true_deg']:.0f}° | "
                         f"{np.mean([g['measured_deg'] for g in got]):.1f}° | {np.mean([g['baseline_deg'] for g in got]):.1f}° | "
                         f"{np.mean([g['worst_bone'] == limb['true_bone'] for g in got]) * 100:.0f}% | "
                         f"{np.mean([g['worst_part'] == g['true_part'] for g in got]) * 100:.0f}% |")

    # Sweeps.
    def sweep_table(sweep, title, note, scope):
        nonlocal lines
        groups = _group(rows, sweep)
        if not groups:
            return groups
        lines += ["", f"## {title}", "", note, "",
                  "| case | coverage | window MAE (ms) | 95th pct (ms) | confidently wrong |" + (" unaffected MAE (ms) |" if scope == "affected" else ""),
                  "|---|---|---|---|---|" + ("---|" if scope == "affected" else "")]
        for label, items in groups:
            row = (f"| {label} | {_fmt(_metric(items, scope, 'coverage'), pct=True)} | {_fmt(_metric(items, scope, 'mae_ms'))} | "
                   f"{_fmt(_metric(items, scope, 'p95_ms'))} | {_fmt(_metric(items, scope, 'confidently_wrong'), pct=True)} |")
            if scope == "affected":
                row += f" {_fmt(_metric(items, 'unaffected', 'mae_ms'))} |"
            lines.append(row)
        return groups

    noise = sweep_table("noise", "Keypoint noise", "Gaussian noise on every keypoint, std as a share of body height (1% is about 4 px for a 400 px dancer).", "all")
    rate = sweep_table("frame_rate", "Frame rate", "The same choreography recorded at different frame rates (realistic noise).", "all")
    occl = sweep_table("occlusion", "Occlusion", "Member 2 fully hidden three times. Scored on the windows that overlap the gaps.", "affected")
    sweep_table("leaves_frame", "Leaving the frame", "A member gone for 10 s; another with knees and ankles cut off for 20 s. Scored on the affected windows.", "affected")
    sweep_table("spin", "Fast spins", "Everyone spins 360° in 0.8 s, three times. In 2D the body flattens to a line mid-spin. *Labels swap*: the pose model also swaps left and right while the back faces the camera.", "affected")
    sweep_table("repeated_groove", "Repeated fast groove", "18 s of a 2-pose groove repeating every 0.36 s, shorter than the ±400 ms search, so the correlation has several equal peaks. Compares the Viterbi jump penalty off and on.", "affected")

    limb_groups = _group(rows, "limb_error")
    if limb_groups:
        lines += ["", "## Size of a pose error", "", "Member 2's left elbow off by N degrees for 20 s (realistic noise).", "",
                  "| injected | measured | others on that bone | right bone named |", "|---|---|---|---|"]
        for label, items in limb_groups:
            got = [row["limbs"][0] for row in items]
            lines.append(f"| {label} | {np.mean([g['measured_deg'] for g in got]):.1f}° | {np.mean([g['baseline_deg'] for g in got]):.1f}° | "
                         f"{np.mean([g['worst_bone'] == g['true_bone'] for g in got]) * 100:.0f}% |")

    (out / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    _figures(per_condition, noise, rate, occl, limb_groups, out)
    return summary


def _figures(per_condition, noise, rate, occl, limb_groups, out: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    apply_style()
    fig, ax = plt.subplots(figsize=(6.4, 4.4))
    true = np.array([m["true_ms"] for m in per_condition["clean"][2]])
    lim = (true.min() - 30, true.max() + 30)
    ax.plot(lim, lim, color=MUTED, lw=1, zorder=1)
    for k, (label, color) in enumerate((("clean", SERIES[0]), ("realistic", SERIES[1]))):
        mean, sd, _ = per_condition[label]
        jitter = (k - 0.5) * 4
        ax.errorbar(true + jitter, mean, yerr=sd, fmt="o", ms=7, color=color, ecolor=color, elinewidth=2, capsize=0, label=label, zorder=3,
                    markeredgecolor="white", markeredgewidth=1.5)
    ax.set_xlim(lim)
    ax.set_ylim(lim)
    ax.set_xlabel("true offset (ms, + = behind the group)")
    ax.set_ylabel("measured offset (ms)")
    ax.set_title("Known shifts come back where they were put", loc="left")
    ax.legend(frameon=False, loc="upper left")
    fig.tight_layout()
    fig.savefig(out / "headline_offsets.png", dpi=150)
    plt.close(fig)

    fig, axes = plt.subplots(2, 2, figsize=(10, 7))

    def line(ax, groups, scope, key, xlabel, ylabel, title, scale=1.0, xs=None):
        values = [g[0] for g in groups]
        x = xs if xs is not None else [items[0]["value"] for _, items in groups]
        y = [(_metric(items, scope, key) or np.nan) * scale for _, items in groups]
        ax.plot(x, y, "-o", color=SERIES[0], lw=2, ms=7, markeredgecolor="white", markeredgewidth=1.5)
        for xi, yi in zip(x, y):
            if np.isfinite(yi):
                ax.annotate(f"{yi:.1f}" if scale == 1 else f"{yi:.0f}%", (xi, yi), textcoords="offset points", xytext=(0, 8), ha="center", color=INK, fontsize=9)
        ax.set_xlabel(xlabel)
        ax.set_ylabel(ylabel)
        ax.set_title(title, loc="left")
        finite = [v for v in y if np.isfinite(v)]
        ax.set_ylim(0, (max(finite) if finite else 1) * 1.2)
        if xs is not None:
            ax.set_xticks(xs, [label for label, _ in groups])
        return values

    line(axes[0, 0], noise, "all", "mae_ms", "keypoint noise (% of body height)", "window error (ms)", "Timing error grows with keypoint noise")
    line(axes[0, 1], rate, "all", "mae_ms", "frame rate (fps)", "window error (ms)", "Low frame rates cost precision")
    line(axes[1, 0], occl, "affected", "coverage", "time hidden", "windows still measured (%)", "Hidden members are flagged, not guessed", scale=100, xs=list(range(len(occl))))
    if limb_groups:
        ax = axes[1, 1]
        x = [items[0]["value"] for _, items in limb_groups]
        y = [np.mean([row["limbs"][0]["measured_deg"] for row in items]) for _, items in limb_groups]
        base = [np.mean([row["limbs"][0]["baseline_deg"] for row in items]) for _, items in limb_groups]
        ax.plot([0, max(x)], [0, max(x)], color=MUTED, lw=1)
        ax.plot(x, y, "-o", color=SERIES[0], lw=2, ms=7, markeredgecolor="white", markeredgewidth=1.5, label="member with the error")
        ax.plot(x, base, "-o", color=SERIES[1], lw=2, ms=7, markeredgecolor="white", markeredgewidth=1.5, label="other members, same bone")
        ax.set_xlabel("injected pose error (degrees)")
        ax.set_ylabel("measured (degrees)")
        ax.set_title("Pose errors are measured at their size", loc="left")
        ax.legend(frameon=False, loc="upper left")
    fig.tight_layout()
    fig.savefig(out / "sweeps.png", dpi=150)
    plt.close(fig)
